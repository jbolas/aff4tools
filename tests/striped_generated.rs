/// Volumes disagreeing about one stream are declined, not reconciled.
///
/// Two volumes claiming different chunk sizes for the same stream cannot both
/// be right. Picking a side would produce a digest no one could attribute, so
/// the image must fail to resolve and say why.
#[test]
fn conflicting_stream_metadata_is_declined() {
    let temp = tempfile::tempdir().unwrap();
    let Some(paths) = generate(temp.path(), 2, "matching", "conflicting-chunk-size") else {
        eprintln!("python3 unavailable; skipping");
        return;
    };

    let mut container = open_set(&paths);
    let report = verify_container(&mut container, VerifyOptions { block_hashes: true }).unwrap();

    let declined = report
        .checks
        .iter()
        .find(|c| c.actual.is_empty() && c.coverage == aff4tools::Coverage::WholeImage)
        .expect("the image-level digest must be declined");

    let reason = format!("{:?}", declined.outcome);
    assert!(
        reason.contains("disagree"),
        "the decline must name the disagreement rather than picking a side: {reason}"
    );

    // A conflict is not a mismatch: nothing was recomputed and found wrong.
    assert!(
        !report.has_mismatch(),
        "an unreadable set must not be reported as failing verification"
    );
}

/// Joining volumes must never reduce what gets verified.
///
/// A volume of a set may declare an image of its own, which the primary has
/// never heard of. Resolving every image against the *primary's* graph then
/// failed with "names no data stream" on an image that names one perfectly
/// well — downgrading a digest that verifies when the same file is opened
/// alone, while the headline still read "N of N matched".
///
/// The guard: whatever a volume verifies by itself, it must still verify as
/// part of a set.
#[test]
fn joining_volumes_never_loses_a_check() {
    let temp = tempfile::tempdir().unwrap();
    let Some(paths) = generate(temp.path(), 3, "matching", "none") else {
        eprintln!("python3 unavailable; skipping");
        return;
    };

    // Compared by identity, not count: the volumes of a striped set share
    // objects, so summing per-file totals would triple-count them.
    let matched = |report: &aff4tools::VerificationReport| {
        report
            .checks
            .iter()
            .filter(|c| c.outcome == Outcome::Match)
            .map(|c| (c.subject.as_str().to_owned(), c.predicate.clone()))
            .collect::<std::collections::BTreeSet<_>>()
    };

    let mut alone = std::collections::BTreeSet::new();
    for path in &paths {
        let mut container = Container::open(path).unwrap();
        let report =
            verify_container(&mut container, VerifyOptions { block_hashes: true }).unwrap();
        alone.extend(matched(&report));
    }

    let mut container = open_set(&paths);
    let report = verify_container(&mut container, VerifyOptions { block_hashes: true }).unwrap();
    let joined = matched(&report);

    let lost: Vec<_> = alone.difference(&joined).collect();
    assert!(
        lost.is_empty(),
        "these digests verify when their volume is opened alone but not when \
         it is part of a set — joining lost coverage: {lost:#?}"
    );
}

/// A volume carrying an image of its own keeps it verifiable in a set.
///
/// The regression Fix 2 addressed: `Image::open_in_set` resolved every image
/// against the **primary's** graph. A volume that declares an image the primary
/// has never heard of then failed with "names no data stream" — a false
/// statement about an intact container, and a digest silently downgraded from
/// MATCH to a decline.
///
/// Built from a striped set plus a *generated single* container, which declares
/// an image of its own. They are not one striped set — that is the point: the
/// primary's graph cannot describe the second volume's image.
///
/// The single container is generated rather than taken from the corpus so this
/// test needs no `--features corpus`; the striped half comes from the generator
/// too, so the two ARN families cannot collide.
#[test]
fn an_image_declared_by_only_one_volume_still_verifies() {
    let temp = tempfile::tempdir().unwrap();

    let striped_dir = temp.path().join("striped");
    std::fs::create_dir_all(&striped_dir).unwrap();
    let Some(striped) = generate(&striped_dir, 2, "matching", "none") else {
        eprintln!("python3 unavailable; skipping");
        return;
    };

    let solo_dir = temp.path().join("solo");
    std::fs::create_dir_all(&solo_dir).unwrap();
    let script = Path::new(env!("CARGO_MANIFEST_DIR")).join("utilities/create_test_aff4.py");
    let solo_path = solo_dir.join("one.aff4");
    let result = Command::new("python3")
        .arg(&script)
        .arg("--bevies")
        .arg("4")
        .arg("--chunk-size")
        .arg("512")
        .arg("--chunks-in-segment")
        .arg("1")
        .arg(&solo_path)
        .output()
        .unwrap();
    assert!(result.status.success());

    // Primary is a stripe; the solo container joins as a second volume whose
    // image the primary has never declared.
    let paths = vec![striped[0].clone(), solo_path];

    // What the second file verifies on its own.
    let mut solo = Container::open(&paths[1]).unwrap();
    let solo_report = verify_container(&mut solo, VerifyOptions { block_hashes: true }).unwrap();
    let solo_matches: std::collections::BTreeSet<_> = solo_report
        .checks
        .iter()
        .filter(|c| c.outcome == Outcome::Match)
        .map(|c| (c.subject.as_str().to_owned(), c.predicate.clone()))
        .collect();
    assert!(!solo_matches.is_empty());

    // The same file as the *second* volume of a set, so the primary's graph
    // knows nothing of its image.
    let mut container = open_set(&paths);
    let report = verify_container(&mut container, VerifyOptions { block_hashes: true }).unwrap();
    let joined: std::collections::BTreeSet<_> = report
        .checks
        .iter()
        .filter(|c| c.outcome == Outcome::Match)
        .map(|c| (c.subject.as_str().to_owned(), c.predicate.clone()))
        .collect();

    let lost: Vec<_> = solo_matches.difference(&joined).collect();
    assert!(
        lost.is_empty(),
        "a second volume's own image must stay verifiable when it is not the \
         primary; these were lost: {lost:#?}"
    );
}
